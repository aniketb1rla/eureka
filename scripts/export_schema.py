"""Writes deploy/supabase.sql from the app's table definitions, so the two can't drift apart.

    python -m scripts.export_schema
"""
from __future__ import annotations

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from studio.config import ROOT
from studio.db import metadata

OUTPUT = ROOT / "deploy" / "supabase.sql"
BUCKET = "studio-private"

HEADER = """-- Generated by scripts/export_schema.py. Run this once in the Supabase SQL editor.
-- It's safe to run again: it only creates what's missing.
--
-- The app connects as the database owner from the server. Browsers never talk to these tables, so
-- row level security is on with no policies and the public API roles get no access at all.
"""


def build() -> str:
    dialect = postgresql.dialect()
    parts = [HEADER]
    for table in metadata.sorted_tables:
        create = str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip()
        parts.append(create + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            parts.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)).strip() + ";\n")
        parts.append(f"alter table {table.name} enable row level security;")
        parts.append(f"revoke all on table {table.name} from anon, authenticated;\n")
    parts.append("-- Private file storage. Files only leave through short-lived links the server signs after checking ownership.")
    parts.append(f"insert into storage.buckets (id, name, public) values ('{BUCKET}', '{BUCKET}', false)\n"
                 "  on conflict (id) do update set public = false;\n")
    return "\n".join(parts)


def main() -> None:
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
